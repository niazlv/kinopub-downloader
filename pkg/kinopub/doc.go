// Package kinopub — публичный клиент JSON API kino.pub.
//
// Это библиотека, а не сервис. Здесь нет и не должно появиться ни сетевого
// слушателя, ни RPC-сервера: встраивание сервера в утилиту превратило бы
// поверхность атаки CLI в поверхность атаки демона. Тот, кому нужен сетевой
// доступ, поднимает его у себя поверх этой библиотеки.
//
// Пакет публичный намеренно. Всё остальное в репозитории лежит под internal/
// и потому недоступно другим модулям — сюда вынесено ровно то, что является
// переиспользуемой библиотекой, а не деталью реализации загрузчика. CLI
// пользуется этим же пакетом: реализация одна, расхождения между «версией для
// CLI» и «версией для API» невозможны by construction.
//
// Пакет НЕ зависит от internal/domain: доменные типы загрузчика не должны
// протекать в публичную сигнатуру, иначе внешний потребитель не сможет
// назвать типы, которые видит.
package kinopub
